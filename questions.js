/* ============================================================================
   СЛУЖЕБНОЕ: выборка вопросов и проверка сетки.
   QDB.pick(cat, tier, used)      — случайный неиспользованный вопрос категории.
   QDB.pickRole(role, tier, used) — то же для фланга «ВАША ПОЗИЦИЯ» (по метке амплуа).
   QDB.audit()                    — отчёт по сетке категорий, по ролям и по дублям.
============================================================================ */
const QDB = {
  all: QUESTIONS,
  cats: CATS,
  roles: ROLES,
  tierByStep(step){ return TIER_BY_STEP[Math.max(0, Math.min(14, step-1))]; },

  /* Все вопросы категории и сложности. */
  pool(cat, tier){ return QUESTIONS.filter(q => q.cat===cat && q.tier===tier); },
  /* Все вопросы, помеченные амплуа, нужной сложности. */
  rolePool(role, tier){ return QUESTIONS.filter(q => q.role===role && q.tier===tier); },

  /* Общая выборка: свежий вопрос нужной сложности из заданного отбора.
     Если свежих нет — расширяем поиск на соседние сложности, затем на весь отбор,
     затем на всю базу: лучше вопрос «не по уровню», чем пустой экран. */
  pickWhere(match, tier, used){
    const fresh = arr => arr.filter(q => !used.has(q.id));
    const at = t => QUESTIONS.filter(q => match(q) && q.tier===t);
    let p = fresh(at(tier));
    if(!p.length){
      for(const d of [1,-1,2,-2,3,-3,4,-4]){
        const t = tier + d;
        if(t < 1 || t > 5) continue;
        p = fresh(at(t));
        if(p.length) break;
      }
    }
    if(!p.length) p = fresh(QUESTIONS.filter(match));
    if(!p.length) p = fresh(QUESTIONS);
    if(!p.length) p = QUESTIONS.filter(match);      // отбор исчерпан — разрешаем повтор
    if(!p.length) p = QUESTIONS.slice();
    return p[Math.floor(Math.random()*p.length)];
  },
  pick(cat, tier, used){      return this.pickWhere(q => q.cat===cat,   tier, used); },
  pickRole(role, tier, used){ return this.pickWhere(q => q.role===role, tier, used); },

  /* Индекс верного ответа: явное поле c, иначе первый вариант. */
  correctIndex(q){ return Number.isInteger(q.c) ? q.c : 0; },

  /* Проверка базы: заполненность сетки «категория × сложность» и «амплуа × сложность»,
     повторы id, битые записи. */
  audit(min=3){
    const problems = [];

    const rows = [];
    for(const cat of Object.keys(CATS)){
      const row = { cat, name:CATS[cat].name, total:0 };
      for(let t=1;t<=5;t++){
        const n = this.pool(cat,t).length;
        row["t"+t] = n; row.total += n;
        if(n < min) problems.push(`мало вопросов: ${CATS[cat].short} / сложность ${t} — ${n} из ${min}`);
      }
      rows.push(row);
    }

    /* Роли: фланг «ВАША ПОЗИЦИЯ» берёт вопросы отсюда, поэтому дыры здесь так же вредны. */
    const roleRows = [];
    for(const role of Object.keys(ROLES)){
      const row = { role, name:ROLES[role].short, total:0 };
      for(let t=1;t<=5;t++){
        const n = this.rolePool(role,t).length;
        row["t"+t] = n; row.total += n;
        if(n < min) problems.push(`мало меток role: ${ROLES[role].short} / сложность ${t} — ${n} из ${min}`);
      }
      roleRows.push(row);
    }

    const seen = new Set();
    for(const q of QUESTIONS){
      if(seen.has(q.id)) problems.push(`дубль id: ${q.id}`);
      seen.add(q.id);
      if(!Array.isArray(q.a) || q.a.length !== 4) problems.push(`${q.id}: нужно ровно 4 варианта ответа`);
      if(!q.q || !q.q.trim()) problems.push(`${q.id}: пустой текст вопроса`);
      if(new Set(q.a).size !== (q.a||[]).length) problems.push(`${q.id}: одинаковые варианты ответа`);
      if(!CATS[q.cat]) problems.push(`${q.id}: неизвестная категория «${q.cat}»`);
      if(q.role && !ROLES[q.role]) problems.push(`${q.id}: неизвестное амплуа «${q.role}»`);
      if(!(q.tier>=1 && q.tier<=5)) problems.push(`${q.id}: сложность вне диапазона 1..5`);
    }

    if(console.table){ console.table(rows); console.table(roleRows); }
    const tagged = QUESTIONS.filter(q=>q.role).length;
    console.log(`Всего вопросов: ${QUESTIONS.length}, из них с меткой амплуа: ${tagged}`);
    if(problems.length){ console.warn("Замечания:"); problems.forEach(p=>console.warn(" • "+p)); }
    else console.log("Сетка заполнена, замечаний нет.");
    return { total:QUESTIONS.length, tagged, rows, roleRows, problems };
  },
};
